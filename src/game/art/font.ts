export const FONT_CHARS = Object.keys(GLYPHS).join('');
export const FONT_CELL_W = 5;
export const FONT_CELL_H = 7;

/** One row of white glyphs with dark outlines; tint it at draw time. */
export function buildFontSheet(): HTMLCanvasElement {
  const chars = FONT_CHARS;
  const p = new Px(chars.length * FONT_CELL_W, FONT_CELL_H);
  [...chars].forEach((ch, i) => {
    const g = GLYPHS[ch];
    const ox = i * FONT_CELL_W + 1;
    const oy = 1;
    for (let y = 0; y < 5; y++)
      for (let x = 0; x < 3; x++) {
        if (g[y][x] !== '1') continue;
        for (let dy = -1; dy <= 1; dy++)
          for (let dx = -1; dx <= 1; dx++) {
            if (Math.abs(dx) + Math.abs(dy) !== 1) continue;
            const nx = x + dx;
            const ny = y + dy;
            if (nx >= 0 && ny >= 0 && nx < 3 && ny < 5 && g[ny][nx] === '1') continue;
            p.set(ox + nx, oy + ny, '#1b1020');
          }
      }
    for (let y = 0; y < 5; y++) for (let x = 0; x < 3; x++) if (g[y][x] === '1') p.set(ox + x, oy + y, '#ffffff');
  });
  return p.canvas;
}
